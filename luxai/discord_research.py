"""Source-backed research to a specifically confirmed Discord DM.

This is a dedicated workflow, not a generic screenshot click. The bot finds
a cited article, searches Discord Quick Switcher for @recipient, visually
validates a match and the DM composer, drafts a message, and waits for an
explicit user decision before pressing Enter. It never claims delivery.
"""
from __future__ import annotations

from dataclasses import dataclass
import ctypes
from ctypes import wintypes
import json
import os
import re
import sys
import time
import urllib.parse
import urllib.request

TOPIC_LIMIT = 110
USER_LIMIT = 48


def validate_discord_plain_message(value: object) -> str:
    """Message content is data supplied by the user, never generated by a screenshot."""
    if (not isinstance(value, str) or
            not 1 <= len(value.strip()) <= 350 or
            any(ord(c) < 32 or ord(c) == 127 for c in value)):
        raise ValueError("Текст сообщения должен быть одной строкой до 350 символов")
    return value.strip()


def validate_discord_text_target(value: object) -> tuple[str, str]:
    """Stable transport: spoken recipient||exact message, no remote code."""
    if not isinstance(value, str) or value.count("||") != 1:
        raise ValueError("Укажите имя пользователя и точный текст сообщения")
    person, content = value.split("||", 1)
    from luxai.discord_screen_review import validate_discord_review_user
    return validate_discord_review_user(person), validate_discord_plain_message(content)


def validate_research_dm_target(value: object) -> tuple[str, str]:
    if not isinstance(value, str) or "||" not in value:
        raise ValueError("Укажите тему и пользователя Discord: Тема||Имя")
    topic, username = value.rsplit("||", 1)
    topic, username = topic.strip(), username.strip().lstrip("@")
    if (not 2 <= len(topic) <= TOPIC_LIMIT or
            not 2 <= len(username) <= USER_LIMIT or
            any(ord(c) < 32 or c in "<>|" for c in topic + username) or
            not re.fullmatch(r"[\w.\- ]{2,48}", username, re.UNICODE)):
        raise ValueError("Неверная тема или имя пользователя Discord")
    return topic, username


def detect_research_dm_request(text: str) -> tuple[str, str] | None:
    """Detect the user's full multi-stage instruction, not arbitrary clicks."""
    phrase = str(text or "").strip()
    lower = phrase.casefold()
    if not (
        re.search(r"(?i)(?:информац|сведени|information|informați|informati|найди|find)", lower)
        and re.search(r"(?i)(?:discord|дискорд|дисси|dessie|в десси|в дисе)", lower)
        and re.search(r"(?i)(?:отправ|напиши|send|trimite|сообщени|message|поставь)", lower)
    ):
        return None
    # Voice recognition may spell Discord/username differently. Extract a
    # candidate, but the recipient must be confirmed again before sending.
    topic_match = re.search(
        r"(?is)(?:информаци[юя]\s+(?:про|об|о)|"
        r"information about|informați[ei]\s+despre|informatii\s+despre)"
        r"\s+(.+?)(?=\s+(?:потом|затем|then|apoi|и\s+(?:нажми|отправ|открой))\b|$)",
        phrase,
    )
    user_match = re.search(
        r"(?i)(?:пользовател[ья]\s+|user(?:name)?\s+|utilizator(?:ul)?\s+|@)"
        r"([\w.\-]{2,48})",
        phrase,
    )
    if not topic_match or not user_match:
        return None
    try:
        return validate_research_dm_target(
            topic_match.group(1).strip(" ,.!?") + "||" + user_match.group(1)
        )
    except ValueError:
        return None


def get_wikipedia_summary(topic: str) -> tuple[str, str]:
    """Real ru.wikipedia.org TextExtracts query; never invent article text."""
    topic, _ = validate_research_dm_target(topic + "||testuser")
    args = urllib.parse.urlencode({
        "action": "query", "generator": "search", "gsrsearch": topic,
        "gsrlimit": "1", "prop": "extracts", "exintro": "1",
        "explaintext": "1", "exchars": "650", "format": "json", "formatversion": "2",
    })
    url = "https://ru.wikipedia.org/w/api.php?" + args
    req = urllib.request.Request(url, headers={
        "User-Agent": "LuxAI-DesktopAssistant/0.2 (Wikipedia summary; non-bot desktop client)",
        "Accept": "application/json",
    })
    with urllib.request.urlopen(req, timeout=14) as response:
        if response.status != 200:
            raise OSError("Wikipedia API returned an error")
        payload = json.loads(response.read(160_000).decode("utf-8"))
    pages = payload.get("query", {}).get("pages", [])
    if not isinstance(pages, list) or len(pages) != 1:
        raise ValueError("Wikipedia did not find a unique relevant article")
    page = pages[0]
    title = str(page.get("title", "")).strip()
    extract = re.sub(r"\s+", " ", str(page.get("extract", ""))).strip()
    if not title or len(extract) < 45:
        raise ValueError("Wikipedia has no usable article text for this topic")
    # Cite the actual source; no hallucinated article or source.
    link = "https://ru.wikipedia.org/wiki/" + urllib.parse.quote(
        title.replace(" ", "_"), safe="()_"
    )
    limit = max(105, 336 - len(title) - len(link))
    snippet = extract[:limit].rsplit(" ", 1)[0].rstrip(" ,;:-")
    # One visual line: inserting a newline into Discord may send before
    # the explicit final user confirmation on some client versions.
    body = f"{title}: {snippet}…  Источник: {link}"
    if len(body.encode("utf-16-le")) // 2 > 350:
        raise ValueError("Article preview exceeds message size limit")
    return body, link


def find_discord_window() -> int:
    """Identify Discord by the real process image, not window title alone."""
    if sys.platform != "win32":
        raise OSError("This workflow requires Windows Discord desktop")
    import psutil
    user32 = ctypes.windll.user32
    user32.IsWindowVisible.argtypes = [wintypes.HWND]
    user32.IsWindowVisible.restype = wintypes.BOOL
    user32.GetWindow.argtypes = [wintypes.HWND, wintypes.UINT]
    user32.GetWindow.restype = wintypes.HWND
    user32.GetWindowThreadProcessId.argtypes = [
        wintypes.HWND, ctypes.POINTER(wintypes.DWORD),
    ]
    user32.GetWindowTextW.argtypes = [
        wintypes.HWND, wintypes.LPWSTR, ctypes.c_int,
    ]
    handles = []

    @ctypes.WINFUNCTYPE(wintypes.BOOL, wintypes.HWND, wintypes.LPARAM)
    def collect(hwnd, extra):
        if not user32.IsWindowVisible(wintypes.HWND(hwnd)) or user32.GetWindow(wintypes.HWND(hwnd), 4):
            return True
        pid = wintypes.DWORD()
        user32.GetWindowThreadProcessId(wintypes.HWND(hwnd), ctypes.byref(pid))
        try:
            process_name = psutil.Process(pid.value).name().casefold()
        except (psutil.NoSuchProcess, psutil.AccessDenied, OSError):
            return True
        if process_name in {"discord.exe", "discordptb.exe", "discordcanary.exe"}:
            title_buffer = ctypes.create_unicode_buffer(260)
            user32.GetWindowTextW(wintypes.HWND(hwnd), title_buffer, len(title_buffer))
            if "discord" in title_buffer.value.casefold():
                handles.append(int(hwnd))
        return True
    user32.EnumWindows(collect, 0)
    if len(handles) != 1:
        raise ValueError(
            "Discord должен быть открыт в одном окне. Запустите Discord и повторите команду."
        )
    return handles[0]


def focus_discord(hwnd: int) -> None:
    if sys.platform != "win32":
        raise OSError("Windows required")
    from luxai.screen_interact import _valid_external_window, _foreground_hwnd
    pid, title = _valid_external_window(hwnd)
    import psutil
    if psutil.Process(pid).name().casefold() not in {
        "discord.exe", "discordptb.exe", "discordcanary.exe",
    }:
        raise ValueError("Selected window is not the Discord application")
    user32 = ctypes.windll.user32
    user32.ShowWindow(wintypes.HWND(hwnd), 9)  # restore; does not minimize user windows
    user32.SetForegroundWindow(wintypes.HWND(hwnd))
    time.sleep(0.22)
    if _foreground_hwnd() != hwnd:
        raise RuntimeError("Could not focus Discord window")


@dataclass(frozen=True)
class DiscordDraft:
    hwnd: int
    username: str
    message: str
    source_url: str
    composer_point: tuple[int, int]
    # The screenshot is not retained in this object.


def prepare_discord_draft(planner, target: str, *,
                          confirm_candidate=None, cancelled=None,
                          message_override=None) -> DiscordDraft:
    """Visually inspect the DM list BEFORE resorting to Discord search.

    The user consents in the UI to at most five cloud screenshots across this
    preparation and the later separately approved send. A differently spelled
    visible contact ALWAYS needs independent user confirmation before a click.
    The actual displayed name is verified again in the DM header and on send.
    """
    from luxai.visual_click import capture_window, find_visual_target, click_visual_target
    from luxai.discord_contact_vision import (
        locate_visible_contact, same_discord_name, search_alias,
    )
    from luxai.desktop_actions import _type_unicode_windows
    from luxai.discord_search_guard import verified_discord_search

    def abort_if_cancelled():
        if cancelled is not None and cancelled():
            raise RuntimeError("Discord command cancelled")

    topic, username = validate_research_dm_target(target)
    abort_if_cancelled()
    if message_override is None:
        message, source_url = get_wikipedia_summary(topic)
    else:
        message = validate_discord_plain_message(message_override)
        source_url = ""
    abort_if_cancelled()
    hwnd = find_discord_window()
    focus_discord(hwnd)
    abort_if_cancelled()

    # A contact may already be visible in the direct-message list, even when
    # spoken Cyrillic differs from its English handle. No blind search first.
    initial = capture_window(hwnd)
    candidate = locate_visible_contact(planner, initial, username)
    selected = initial

    if candidate is None:
        # Search is a fallback, not a prerequisite for visually selecting a
        # contact. This avoids hiding visible DMs under Quick Switcher.
        selected = verified_discord_search(
            planner, hwnd, "@" + username, cancelled=cancelled,
        )
        candidate = locate_visible_contact(
            planner, selected, username, quick_switcher=True
        )
        if candidate is None:
            alias = search_alias(username)
            if alias:
                # Latin variants remain search hints, never identity proof.
                selected = verified_discord_search(
                    planner, hwnd, "@" + alias, replace=True, cancelled=cancelled,
                )
                candidate = locate_visible_contact(
                    planner, selected, username, quick_switcher=True
                )

    if candidate is None:
        raise ValueError(
            "Discord: пользователь не найден визуально ни в списке, "
            "ни через поиск. Укажите имя, как оно отображается в Discord."
        )

    displayed = candidate.display_name
    # Similar-sounding names are not proof of recipient identity. Explicit
    # human approval is mandatory when the displayed name differs.
    if not same_discord_name(username, displayed):
        if confirm_candidate is None or not confirm_candidate(username, displayed):
            raise ValueError(
                "Discord: имя на снимке отличается от произнесённого; "
                "выбор получателя отменён, ничего не отправлено."
            )
    abort_if_cancelled()
    # The confirmation dialog briefly takes focus away from Discord.
    # Restore the *same verified* application before a screenshot-based click.
    focus_discord(hwnd)
    abort_if_cancelled()
    click_visual_target(selected, candidate.point, 1)
    time.sleep(0.4)
    abort_if_cancelled()
    from luxai.discord_navigation import _chat_header_ok
    try:
        conversation = _chat_header_ok(planner, hwnd, displayed)
    except (ValueError, RuntimeError):
        # Quick Switcher may only close its search overlay on the first
        # click. Do not type into a stale / unrelated chat.
        focus_discord(hwnd)
        new_capture = capture_window(hwnd)
        again = locate_visible_contact(planner, new_capture, displayed)
        if again is None or not same_discord_name(again.display_name, displayed):
            raise ValueError(
                "Discord: поиск закрылся без открытия нужного диалога; "
                "контакт не найден повторно."
            )
        abort_if_cancelled()
        click_visual_target(new_capture, again.point, 1)
        time.sleep(0.4)
        abort_if_cancelled()
        conversation = _chat_header_ok(planner, hwnd, displayed)
    composer = find_visual_target(
        planner,
        f"Discord INDIVIDUAL DM HEADER must identify the user {displayed!r} "
        f"(requested voice spelling was {username!r}). Find the MESSAGE COMPOSER "
        "at the bottom ONLY if the header visibly identifies that same "
        "individual and not a group or channel; otherwise found:false.",
        conversation,
    )
    abort_if_cancelled()
    click_visual_target(conversation, composer, 1)
    # Typing is not sending: no Enter until the user confirms in the Qt UI.
    if "\n" in message or "\r" in message:
        raise ValueError("Message contains an unsafe newline")
    _type_unicode_windows(message)
    return DiscordDraft(hwnd, displayed, message, source_url, composer)

def submit_discord_draft(draft: DiscordDraft, planner, *, cancelled=None) -> str:
    """Approve recipient visually; restore the EXACT approved draft, then send.

    The previous vision request expected an AI to OCR every character of a
    long, percent-encoded Wikipedia link in a downscaled screenshot. This
    often reported ambiguity even when the Discord composer was correct.
    Instead we verify the specific DM header and the real editor using a
    FRESH screenshot, then replace its text with the already approved draft
    using native Unicode keyboard input. The replacement is intentional
    and disclosed in the separate send-confirmation dialog.

    Never send if the actual recipient, composer, Windows focus or native
    keyboard operation cannot be verified. No clipboard access is needed.
    """
    if not isinstance(draft, DiscordDraft):
        raise ValueError("No prepared Discord draft")
    if planner is None:
        raise ValueError("A vision-capable AI is required to verify the recipient")
    if not isinstance(draft.message, str) or not draft.message.strip():
        raise ValueError("Prepared Discord draft is empty")
    if "\n" in draft.message or "\r" in draft.message:
        raise ValueError("Prepared Discord message has unsafe line breaks")
    if cancelled is not None and cancelled():
        raise RuntimeError("Discord send cancelled")

    from luxai.visual_click import (
        capture_window, find_visual_target, click_visual_target,
    )
    from luxai.desktop_actions import _type_unicode_windows
    from luxai.screen_interact import _valid_external_window, _foreground_hwnd
    import pyautogui

    focus_discord(draft.hwnd)
    current = capture_window(draft.hwnd)
    # Do not require visual OCR of the long full draft and escaped URL.
    # The recipient must match exactly and the clickable control must be the
    # editor of THIS chat, not a sidebar, search field or a message bubble.
    point = find_visual_target(
        planner,
        "Discord INDIVIDUAL DIRECT MESSAGE: first verify that the visible "
        f"CURRENT CHAT HEADER unambiguously names the recipient {draft.username!r}. "
        "Find the CENTER of this same DM's BOTTOM MESSAGE COMPOSER (editable "
        "textbox), NOT any sent message, channel, group chat, search box, "
        "profile field or attachment. The composer may currently hold a "
        "long multiline-looking DRAFT and a percent-encoded Wikipedia URL. "
        "Do NOT try to OCR or match every character of the draft: Jarvis "
        "will replace the textbox contents with the exact text separately "
        "approved by its user. If the actual header is not the intended "
        "individual or the composer cannot be identified unambiguously, "
        "return found:false.",
        current,
    )
    if cancelled is not None and cancelled():
        raise RuntimeError("Discord send cancelled")
    # Never use the previously stored composer coordinate.
    click_visual_target(current, point, 1)
    if cancelled is not None and cancelled():
        raise RuntimeError("Discord send cancelled")

    # The user approved the exact contents in the separate Qt preview. The
    # current editable draft is replaced rather than trusting blurry OCR or
    # sending something potentially changed after that approval.
    pyautogui.hotkey("ctrl", "a", interval=0.07)
    if cancelled is not None and cancelled():
        raise RuntimeError("Discord send cancelled")
    _type_unicode_windows(draft.message)
    if cancelled is not None and cancelled():
        raise RuntimeError("Discord send cancelled")

    # The captured window must STILL be the same foreground process/title.
    if _foreground_hwnd() != current.hwnd:
        raise RuntimeError("Discord focus changed while preparing the approved text")
    pid, title = _valid_external_window(current.hwnd)
    if pid != current.pid or title != current.title:
        raise RuntimeError("Discord window changed while preparing the approved text")

    pyautogui.press("enter")
    return (
        "Enter отправлен в визуально проверенный Discord DM после "
        "повторного ввода одобренного текста. Доставку сообщения "
        "подтвердить не могу — проверьте историю переписки."
    )
